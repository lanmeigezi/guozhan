/**
 * 把国战确定性内核打包成 uno-bt 的零依赖 ES 模块。
 *
 * 产物：<UNO_BT_ROOT>/core/src/guozhan/engine.bundle.js
 *   · 只含 core / protocol / 启发式 AI / 自我复盘 / 随机地图；
 *   · 不含任何 LLM 客户端、HTTP/WS/MCP 服务端代码或 node 内置模块；
 *   · 剧本数据在构建期装配后内嵌，运行期不需要 fs。
 *
 * 用法：node --experimental-strip-types scripts/build-uno-engine.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { loadScenario } from '../src/server/config-loader.ts';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const UNO_BT_ROOT = process.env.UNO_BT_ROOT || 'D:/测试/uno-bt';
const OUT = join(UNO_BT_ROOT, 'core', 'src', 'guozhan', 'engine.bundle.js');
const GENERATED = join(ROOT, 'src', 'integration', 'uno-data.generated.ts');

function readJson(path: string): any {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function safeMeta(meta: any, startTurn?: number): Record<string, unknown> {
  return {
    id: meta.id,
    name: meta.name,
    description: meta.description ?? '',
    maxTurns: meta.maxTurns,
    moduleOrder: meta.moduleOrder,
    milestones: meta.milestones ?? [],
    ...(startTurn !== undefined ? { startTurn } : {}),
  };
}

function colorsOf(layout: any): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [fid, color] of Object.entries(layout?.factionColors ?? {})) {
    if (typeof color === 'string' && /^#[0-9a-fA-F]{6}$/.test(color)) out[fid] = color.toLowerCase();
  }
  return out;
}

function aggressionOf(factionsDoc: any): Record<string, number> {
  const out: Record<string, number> = {};
  for (const f of factionsDoc?.factions ?? []) {
    out[String(f.id)] = Number(f.personality?.aggression ?? 0.5);
  }
  return out;
}

// ── 固定地图剧本：构建期完整装配 ──
const fixed: Record<string, unknown> = {};
for (const id of ['iron-front', 'warring-states', 'warring-states-full', 'frontier']) {
  const loaded = loadScenario(id);
  const factionsDoc = readJson(join(ROOT, 'config', 'scenarios', id, 'factions.json'));
  fixed[id] = {
    meta: safeMeta(loaded.meta),
    world: loaded.world,
    initialState: loaded.initialState,
    mapLayout: loaded.mapLayout,
    colors: colorsOf(loaded.mapLayout),
    aggression: aggressionOf(factionsDoc),
  };
}

// ── 随机地图剧本：运行期按种子生成地图，构建期只烘焙规则与帮助文本 ──
const TEMPLATE_SEED = 'uno-bt-template-v1';
const loadedRandom = loadScenario('random-front-v2', TEMPLATE_SEED);
const scenarioJson = readJson(join(ROOT, 'config', 'scenarios', 'random-front-v2', 'scenario.json'));
const randomRoster = readJson(join(ROOT, 'config', 'scenarios', 'random-front-v2', 'factions.json'));
const randomUnits = readJson(join(ROOT, 'config', 'scenarios', 'random-front-v2', 'units.json'));
const { regions: _regions, waterRoutes: _waterRoutes, contentHash: _contentHash, ...worldBase } = loadedRandom.world;
const random = {
  meta: safeMeta(loadedRandom.meta, scenarioJson.meta?.startTurn ?? 1),
  scenario: { generator: scenarioJson.generator },
  roster: randomRoster,
  unitsDoc: randomUnits,
  worldBase: { ...worldBase, regions: {}, waterRoutes: [], contentHash: 'runtime' },
  layoutHelp: {
    laws: loadedRandom.mapLayout.laws,
    units: loadedRandom.mapLayout.units,
    rules: loadedRandom.mapLayout.rules,
  },
};

// ── 超大陆剧本：同一套生成器，但 12 势力 / 半径 6 ──
const loadedLarge = loadScenario('grand-front', TEMPLATE_SEED);
const largeScenarioJson = readJson(join(ROOT, 'config', 'scenarios', 'grand-front', 'scenario.json'));
const largeRoster = readJson(join(ROOT, 'config', 'scenarios', 'grand-front', 'factions.json'));
const largeUnits = readJson(join(ROOT, 'config', 'scenarios', 'grand-front', 'units.json'));
const { regions: _largeRegions, waterRoutes: _largeWaterRoutes, contentHash: _largeContentHash, ...largeWorldBase } = loadedLarge.world;
const large = {
  meta: safeMeta(loadedLarge.meta, largeScenarioJson.meta?.startTurn ?? 1),
  scenario: { generator: largeScenarioJson.generator },
  roster: largeRoster,
  unitsDoc: largeUnits,
  worldBase: { ...largeWorldBase, regions: {}, waterRoutes: [], contentHash: 'runtime' },
  layoutHelp: {
    laws: loadedLarge.mapLayout.laws,
    units: loadedLarge.mapLayout.units,
    rules: loadedLarge.mapLayout.rules,
  },
};

const dataTs =
  '// AUTO-GENERATED by scripts/build-uno-engine.ts. Do not edit.\n' +
  '// 国战剧本数据快照：不含 LLM/网络/IO 配置。\n' +
  `export const DATA: any = ${JSON.stringify({ fixed, random, large }, null, 2)};\n`;
writeFileSync(GENERATED, dataTs);
console.log(`Wrote ${GENERATED}`);

const result = await build({
  entryPoints: [join(ROOT, 'src', 'integration', 'uno-session.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2020',
  write: false,
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
});

const body = result.outputFiles[0]!.text;
const header =
  '/*! guozhan uno-bt engine — generated by scripts/build-uno-engine.ts.\n' +
  ' *  确定性国战内核 + 启发式 AI + 自我复盘 + 随机六角地图。\n' +
  ' *  不含外部 LLM 客户端/HTTP/MCP/fs；请勿手改，改 guozhan 源码后重新生成。\n' +
  ' */\n';
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, header + body);
console.log(`Wrote ${OUT} (${body.length} bytes)`);
