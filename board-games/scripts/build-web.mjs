// build-web.mjs — zero-dependency ES module bundler for the core.
//
// Android WebView does not reliably load ES modules from file:// URLs (they are
// treated as an opaque origin), so the app needs the core flattened into a
// single classic script that exposes a global `window.UNOKU`. This tool does
// exactly that for the core's simple ESM (named imports/exports only, no default
// exports, no dynamic imports, no circular dependencies).
//
// Usage: node scripts/build-web.mjs
//   in:  core/src/*.js (entry: core/src/index.js)
//   out: app/src/main/assets/www/uno-core.bundle.js

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const CORE = path.join(ROOT, 'core', 'src');
const ENTRY = path.join(CORE, 'index.js');
const OUT = path.join(ROOT, 'app', 'src', 'main', 'assets', 'www', 'uno-core.bundle.js');

// ---- parse one module into { url, dir, code, imports, reExports, exportNames } ----
function parseModule(absUrl) {
  let code = fs.readFileSync(absUrl, 'utf8');

  const imports = [...code.matchAll(/import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?/g)].map((mm) => ({
    path: mm[2],
    names: parseNameList(mm[1]),
  }));
  const reExports = [...code.matchAll(/export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?/g)].map((mm) => ({
    path: mm[2],
    names: parseNameList(mm[1]),
  }));

  // remove import + re-export statements
  code = code.replace(/import\s*\{[^}]*\}\s*from\s*['"][^'"]+['"]\s*;?/g, '');
  code = code.replace(/export\s*\{[^}]*\}\s*from\s*['"][^'"]+['"]\s*;?/g, '');

  // exported declarations
  const declExports = [...code.matchAll(/export\s+(function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/g)];
  const plainExports = [...code.matchAll(/export\s*\{([^}]*)\}\s*;?/g)];

  // strip the export keyword from declarations + plain lists
  code = code.replace(/export\s+(function|class|const|let|var)\s+([A-Za-z_$][\w$]*)/g, '$1 $2');
  code = code.replace(/export\s*\{[^}]*\}\s*;?/g, '');

  const exportNames = new Set();
  for (const d of declExports) exportNames.add(d[2]);
  // Plain `export { a, b as c }` lists are used by generated bundles (esbuild).
  // parseNameList returns {local, imported}; the exported binding name is `local`.
  for (const p of plainExports) for (const n of parseNameList(p[1])) exportNames.add(n.local);

  return { url: absUrl, dir: path.dirname(absUrl), code, imports, reExports, exportNames: [...exportNames] };
}

function parseNameList(s) {
  return s
    .split(',')
    .map((x) => x.trim())
    .filter(Boolean)
    .map((x) => {
      const [local, alias] = x.split(/\s+as\s+/);
      return { local: (alias || local).trim(), imported: local.trim() };
    });
}

// ---- collect all modules reachable from entry ----
const modules = [];
const byUrl = new Map();
function getModule(absUrl) {
  if (byUrl.has(absUrl)) return byUrl.get(absUrl);
  const mod = parseModule(absUrl);
  const idx = modules.length;
  modules.push(mod);
  byUrl.set(absUrl, idx);
  for (const imp of [...mod.imports, ...mod.reExports]) {
    const resolved = path.resolve(mod.dir, imp.path);
    getModule(resolved);
  }
  return idx;
}
const entryIndex = getModule(ENTRY);

// ---- emit the bundle ----
let defs = '';
for (let i = 0; i < modules.length; i++) {
  const m = modules[i];
  const pre = m.imports
    .map(({ path: p, names }) =>
      names.map((n) => `  const ${n.local} = __req(${byUrl.get(path.resolve(m.dir, p))}).${n.imported};`).join('\n')
    )
    .join('\n');
  const rex = m.reExports
    .map(({ path: p, names }) =>
      names.map((n) => `  __exports.${n.local} = __req(${byUrl.get(path.resolve(m.dir, p))}).${n.imported};`).join('\n')
    )
    .join('\n');
  const exps = m.exportNames.map((n) => `  __exports.${n} = ${n};`).join('\n');
  defs += `function __mod${i}(__req, __exports) {\n${pre}\n${m.code}\n${rex}\n${exps}\n}\n`;
}

const runtime = `
var __mods = [${modules.map((_, i) => `__mod${i}`).join(', ')}];
var __cache = [undefined];
function __req(i) {
  if (__cache[i]) return __cache[i];
  var __exports = {};
  __cache[i] = __exports;
  __mods[i](__req, __exports);
  return __exports;
}
var UNOKU = __req(${entryIndex});
`;

const banner = `/*! uno-core bundle — generated by scripts/build-web.mjs. Do not edit; edit core/src instead. */`;
const bundle = banner + '\n(function (global) {\n' + defs + runtime + '\nglobal.UNOKU = UNOKU;\nif (typeof module !== "undefined" && module.exports) module.exports = UNOKU;\n})(typeof window !== "undefined" ? window : globalThis);\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, bundle);
console.log(`Wrote ${OUT} (${modules.length} modules, ${bundle.length} bytes)`);
