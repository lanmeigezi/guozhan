/**
 * 史官统一润色（席位盲化的文本层）
 *
 * 试玩暴露的真实弱点：人机补位用 8 句固定池轮换，人类 / 外部模型席位写个性化台词，
 * 编年史里立刻形成「8 国套语复用 + 4 国个性化」的可见分组，模型虽未必直接下结论，
 * 但足以把少数席位圈进小集合，构成实质性推断线索。
 *
 * 解决方式不是扩大台词池，而是**让所有席位走同一个确定性生成器**：
 * 无论意图来自人类、人机补位还是外部模型，写进权威状态前都由本模块重写 note。
 * 生成只依赖 (seed, turn, civId, type)，与控制者身份完全无关；组合空间约 12×6×12，
 * 多回合也不会出现「某些席位固定用套语」的模式。
 *
 * 设定解释：君主原话由史官以同一笔法转述，因此编年史文体一致。原始 note 不落库、
 * 不进编年史、不进存档，仅存在于本次 HTTP 回执中（提交者自己知道写了什么，不构成泄漏）。
 */
import { createRng } from './rng.js';

const OPENERS = [
    '庙堂议定', '廷议既决', '太史谨记', '是岁', '朝议佥同', '王庭有令',
    '边书上达', '国有常典', '宰辅进言', '岁在此时', '诸侯来告', '简策重书',
];

const CLOSERS = [
    '，以俟来年。', '，不复多议。', '，载于简册。', '，其议遂定。', '，遂付有司。', '，后世可考。',
    '，书之无讳。', '，国有成算。', '，民皆安之。', '，以观其后。', '，立于本纪。', '，毋得更议。',
];

const ACTION_PHRASES = {
    invest: ['沟洫初治', '田畴渐辟', '工役有序', '仓廪稍实', '城邑增修', '水利既举'],
    research: ['简策日增', '历算渐精', '格物有得', '学宫延士', '推步益密', '典籍重辑'],
    expand: ['边氓来附', '疆理稍广', '新邑初立', '斥候及远', '版图增廓', '野人归化'],
    attack: ['甲兵既动', '边烽骤起', '师旅在途', '戎事方殷', '旌旗远指', '战守有备'],
    diplomacy: ['使节往还', '盟书初具', '邻好是修', '聘问不绝', '约剂既成', '唇齿相恤'],
    fortify: ['武库充实', '部伍整饬', '甲仗更新', '城守加严', '戍卒增募', '兵籍再核'],
    stabilize: ['闾里安堵', '赋敛稍平', '民讼日稀', '仓谷赈乏', '户口复业', '境内无事'],
    colonize: ['星槎初发', '远略在海', '舟师指天', '天外置邑', '殖民有籍', '重霄可期'],
};

const GENERIC = ['庶务有章', '国是粗定', '百司奉行', '四境无虞', '政令既行', '职事各举'];

/** @returns {string} 一句史书笔法的中性台词，绝不含身份标记 */
export function courtPhrase(state, decision) {
    const rng = createRng(`${state.seed}::voice::${state.turn}::${decision.civId}::${decision.type}`);
    const opener = rng.pick(OPENERS);
    const pool = ACTION_PHRASES[decision.type] ?? GENERIC;
    const action = rng.pick(pool);
    const closer = rng.pick(CLOSERS);
    return `${opener}，${action}${closer}`;
}
